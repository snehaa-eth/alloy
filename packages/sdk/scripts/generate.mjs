// Regenerates src/generated.ts from packages/contracts (ABIs + deployments) and packages/testnet-env.
// Run: node packages/sdk/scripts/generate.mjs   (after any redeploy or ABI change)
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const abiDir = join(root, "contracts", "abi");
const pick = ["BasketFactory", "Basket", "AlloyRouter", "UniswapV3Adapter", "SimpleFeedGuard", "IAggregatorV3"];
let out = "// AUTO-GENERATED by scripts/generate.mjs. Do not edit by hand.\n\n";
for (const name of pick) {
  const raw = JSON.parse(readFileSync(join(abiDir, `${name}.json`), "utf8"));
  const abi = Array.isArray(raw) ? raw : raw.abi;
  out += `export const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(abi)} as const;\n\n`;
}
const c = JSON.parse(readFileSync(join(root, "contracts", "deployments", "84532.json"), "utf8"));
const t = JSON.parse(readFileSync(join(root, "testnet-env", "deployments", "84532.json"), "utf8"));
out += `export const deployments = ${JSON.stringify({ 84532: { contracts: c, testnetEnv: t } }, null, 2)} as const;\n`;
writeFileSync(join(root, "sdk", "src", "generated.ts"), out);
console.log("wrote src/generated.ts with", pick.length, "ABIs");
