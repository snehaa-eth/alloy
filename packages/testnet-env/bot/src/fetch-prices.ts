/**
 * Deploy-prep helper: fetch CURRENT real prices and write config/prices.json, which
 * script/DeployTestnet.s.sol reads to seed MockPriceFeeds and initialise pool prices.
 *
 *   pnpm prices                      # Coinbase tokenized-stocks API (default)
 *   PRICE_SOURCE=chainlink pnpm prices   # Base-mainnet Chainlink feeds from config/mainnet-feeds.json
 */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { loadConfig, PKG_ROOT } from "./config.js";
import { fmtUsd } from "./math.js";
import { fetchRealPrices } from "./prices.js";

export const TICKERS = ["NVDA", "GOOGL", "MSFT", "TSLA", "AAPL", "AMZN"];

async function main() {
  const cfg = loadConfig();
  const prices = await fetchRealPrices({
    source: cfg.priceSource,
    tickers: TICKERS,
    mainnetFeeds: cfg.mainnetFeeds,
    mainnetRpcUrl: cfg.mainnetRpcUrl,
  });
  const missing = TICKERS.filter((t) => !prices[t]);
  if (missing.length) throw new Error(`no price for ${missing.join(", ")}`);

  const now = Math.floor(Date.now() / 1000);
  const out = {
    fetchedAt: new Date(now * 1000).toISOString(),
    fetchedAtUnix: now,
    decimals: 8,
    note: "USD per raw token, 8 decimals (Chainlink semantics). Generated by `pnpm -C bot prices`.",
    // JSON numbers (not strings) so vm.parseJsonUint reads them; all < 2^53.
    prices: Object.fromEntries(TICKERS.map((t) => [t, Number(prices[t]!.answer)])),
    sources: Object.fromEntries(
      TICKERS.map((t) => [t, { source: prices[t]!.source, observedAt: prices[t]!.observedAt }]),
    ),
  };
  const path = resolve(PKG_ROOT, "config", "prices.json");
  writeFileSync(path, JSON.stringify(out, null, 2) + "\n");
  for (const t of TICKERS) console.log(`${t.padEnd(6)} ${fmtUsd(prices[t]!.answer).padStart(12)}  ${prices[t]!.source}`);
  console.log(`wrote ${path}`);
}

main().catch((e) => {
  console.error(e instanceof Error ? e.message : e);
  process.exit(1);
});
